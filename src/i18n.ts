export function makeT(dict: Record<string, string>) {
  return (key: string, vars?: Record<string, string | number>): string => {
    let s = dict[key] ?? key
    if (vars) for (const k of Object.keys(vars)) s = s.replaceAll(`{${k}}`, String(vars[k]))
    return s
  }
}

